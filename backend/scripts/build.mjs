// Bundles the API with esbuild:
//   dist/server.mjs          → `npm start` on any Node host (Railway, Render, a laptop at the booth)
//   ../frontend/api/index.js → Vercel Function, deployed together with the app (same origin, /api)
import { build } from 'esbuild'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const shared = {
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node20',
  alias: { '@': `${root}../frontend/src` },
  // pg's optional native binding and the embedded dev database are never needed in these bundles
  external: ['pg-native', '@electric-sql/pglite'],
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  legalComments: 'none',
  logLevel: 'info',
}

await build({ ...shared, entryPoints: [`${root}src/server.ts`], outfile: `${root}dist/server.mjs` })
await build({
  ...shared,
  entryPoints: [`${root}src/vercel.ts`],
  outfile: `${root}../frontend/api/index.js`,
  banner: { js: `// GENERATED by backend/scripts/build.mjs – edit backend/src, then run \`npm run build\` in backend/.\n${shared.banner.js}` },
})
